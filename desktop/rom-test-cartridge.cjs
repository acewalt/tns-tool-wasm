// Original NROM cartridge for testing the real NesNspire ARM emulator.
// Generates animated checkerboard graphics. No commercial ROM/data required.
module.exports=function cartridge(){
 const code=[],labels={},fixups=[];
 const label=name=>labels[name]=0x8000+code.length;
 const emit=(...bytes)=>code.push(...bytes);
 const absolute=(op,name)=>{emit(op,0,0);fixups.push({at:code.length-2,name});};
 const branch=(op,name)=>{emit(op,0);fixups.push({at:code.length-1,name,relative:true});};
 label('reset');emit(0x78,0xd8,0xa2,0x40,0x8e,0x17,0x40,0xa2,0xff,0x9a,0xe8,0x8e,0x00,0x20,0x8e,0x01,0x20,0x8e,0x10,0x40);
 label('vblank');emit(0x2c,0x02,0x20);branch(0x10,'vblank');
 emit(0xa9,0x3f,0x8d,0x06,0x20,0xa9,0,0x8d,0x06,0x20,0xa2,0);
 label('paletteLoop');absolute(0xbd,'palette');emit(0x8d,0x07,0x20,0xe8,0xe0,32);branch(0xd0,'paletteLoop');
 emit(0xa9,0x20,0x8d,0x06,0x20,0xa9,0,0x8d,0x06,0x20,0xa2,0,0xa0,4,0xa9,1);
 label('tiles');emit(0x8d,0x07,0x20,0xe8);branch(0xd0,'tiles');emit(0x88);branch(0xd0,'tiles');
 emit(0xa9,0,0x85,0,0x8d,0x05,0x20,0x8d,0x05,0x20,0xa9,0x80,0x8d,0,0x20,0xa9,0x0a,0x8d,1,0x20);
 label('forever');absolute(0x4c,'forever');
 label('nmi');emit(0x48,0xe6,0,0xa9,1,0x8d,0x16,0x40,0xa9,0,0x8d,0x16,0x40,0xad,0x16,0x40,0x29,1);branch(0xf0,'notPressed');
 emit(0xa9,0x2a);branch(0xd0,'setColor');label('notPressed');emit(0xa9,0x16);label('setColor');emit(0x85,1,0xa9,0x3f,0x8d,0x06,0x20,0xa9,1,0x8d,0x06,0x20,0xa5,1,0x8d,0x07,0x20,0xa5,0,0x8d,0x05,0x20,0xa9,0,0x8d,0x05,0x20,0x68,0x40);
 label('palette');for(let i=0;i<8;i++)emit(0x0f,0x16,0x27,0x30);
 for(const f of fixups){const value=labels[f.name];if(value==null)throw Error('Missing label');if(f.relative){const offset=value-(0x8000+f.at+1);if(offset< -128||offset>127)throw Error('Branch range');code[f.at]=offset&255;}else{code[f.at]=value&255;code[f.at+1]=value>>>8;}}
 const out=Buffer.alloc(16+16384+8192);out.write('NES\x1a',0,'binary');out[4]=1;out[5]=1;out.set(code,16);
 out.writeUInt16LE(labels.nmi,16+0x3ffa);out.writeUInt16LE(labels.reset,16+0x3ffc);out.writeUInt16LE(labels.nmi,16+0x3ffe);
 for(let row=0;row<8;row++){out[16+16384+16+row]=row%2?0x55:0xaa;out[16+16384+24+row]=row<4?0xf0:0x0f;}
 return new Uint8Array(out);
};
